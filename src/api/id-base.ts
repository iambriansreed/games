/** How many distinct `adjective-animal` names exist (~20k). */
export const NAME_COUNT = ADJECTIVES.length * ANIMALS.length;

/**
 * Draw a readable name like `brave-otter`. Uniqueness is the caller's job —
 * see `Store.uniqueId`, which redraws until it finds one the table hasn't used.
 */
export function randomName(): string {
    const adjective = ADJECTIVES[crypto.randomInt(ADJECTIVES.length)];
    const animal = ANIMALS[crypto.randomInt(ANIMALS.length)];
    return `${adjective}-${animal}`;
}
